#!/usr/bin/env python3
"""Generate GPT-Neo template token IDs for firmware."""

from __future__ import annotations

import argparse
from pathlib import Path

from transformers import AutoTokenizer


BASE_FRAGMENTS = {
    "SUMMARY": "Summary:",
    "WORDS": "\nWords:",
    "STORY": "\nStory:",
}

CHAT_FRAGMENTS = {
    "CHAT_SYSTEM": "System: ",
    "CHAT_USER": "\nUser: ",
    "CHAT_ASSISTANT": "\nAssistant: ",
}


def c_array(name: str, ids: list[int]) -> str:
    values = ", ".join(str(i) for i in ids)
    return f"static const int {name}[] = {{{values}}};\nstatic const int {name}_LEN = {len(ids)};\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default="models/chinnallm", help="HF tokenizer/model directory")
    parser.add_argument("--out", default="firmware/template_ids_neo.h")
    args = parser.parse_args()

    tok = AutoTokenizer.from_pretrained(args.model, use_fast=True)
    out = Path(args.out)
    text = """/* Generated by tools/gen_template_ids.py. Do not edit by hand. */
#ifndef TEMPLATE_IDS_NEO_H
#define TEMPLATE_IDS_NEO_H

"""
    text += "/* Base instruct template fragments. */\n"
    for key, fragment in BASE_FRAGMENTS.items():
        ids = tok.encode(fragment, add_special_tokens=False)
        text += f"/* {fragment!r} -> {ids} */\n"
        text += c_array(f"NEO_TEMPLATE_{key}", ids)
    text += "\n/* Chat template fragments. */\n"
    for key, fragment in CHAT_FRAGMENTS.items():
        ids = tok.encode(fragment, add_special_tokens=False)
        text += f"/* {fragment!r} -> {ids} */\n"
        text += c_array(f"NEO_TEMPLATE_{key}", ids)
    text += "\n#endif\n"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
