static int wr(const uint8_t *buf, int len) {
    return i2c_write_blocking(OLED_I2C, OLED_ADDR, buf, (size_t)len, false) == len;
}

static void oled_flush(void) {
    static uint8_t out[1025];
    if (!g_ok) return;
    const uint8_t win[] = {0x00, 0x20, 0x00, 0x21, 0x00, 0x7F, 0x22, 0x00, 0x07};
    wr(win, sizeof(win));
    out[0] = 0x40;
    memcpy(out + 1, fb, 1024);
    wr(out, 1025);
}

int oled_init(void) {
    i2c_init(OLED_I2C, 400 * 1000);
    gpio_set_function(OLED_SDA, GPIO_FUNC_I2C);
    gpio_set_function(OLED_SCL, GPIO_FUNC_I2C);
    gpio_pull_up(OLED_SDA);
    gpio_pull_up(OLED_SCL);
    sleep_ms(50);

    static const uint8_t init_seq[] = {
        0x00,       /* control: commands follow */
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
    };
    g_ok = wr(init_seq, (int)sizeof(init_seq));
    if (g_ok) oled_clear();
    return g_ok;
}

void oled_clear(void) {
    if (!g_ok) return;
    memset(fb, 0, sizeof(fb));
    cur_col = 0;
    cur_row = 0;
    oled_flush();
}

static void newline(void) {
    cur_col = 0;
    if (cur_row < 7) {
        cur_row++;
        return;
    }
    /* scroll one text row (one page) up */
    memmove(fb, fb + 128, 1024 - 128);
    memset(fb + 1024 - 128, 0, 128);
}

static void put_char(char c) {
    if (c == '\n') { newline(); return; }
    if (c == '\r') return;
    unsigned char u = (unsigned char)c;
    if (u < 32 || u > 127) u = ' ';
    if (cur_col >= 21) newline();
    uint8_t *dst = fb + cur_row * 128 + cur_col * 6;
    const uint8_t *g = font5x7[u - 32];
    for (int i = 0; i < 5; i++) dst[i] = g[i];
    dst[5] = 0x00;
    cur_col++;
}

void oled_print(const char *s) {
    if (!g_ok || !s || !s[0]) return;
    for (; *s; s++) put_char(*s);
    oled_flush();
}

void oled_meter(int level, int marker) {
    if (!g_ok) return;
    if (level < 0) level = 0;
    if (level > 127) level = 127;
    uint8_t *row = fb + 7 * 128;
    for (int x = 0; x < 128; x++) row[x] = (x < level) ? 0x3C : 0x00;
    if (marker >= 0 && marker < 128) row[marker] = 0xFF;
    const uint8_t win[] = {0x00, 0x20, 0x00, 0x21, 0x00, 0x7F, 0x22, 0x07, 0x07};
    wr(win, sizeof(win));
    static uint8_t out[129];
    out[0] = 0x40;
    memcpy(out + 1, row, 128);
    wr(out, 129);
}
